# DM-LN generator (Section 4, Eq. 18 of the latent NBSR paper).
#
# This is a copy of generate_data_total_rna_imbalance_latent.R with the
# smallest set of changes needed to add the Dirichlet layer between the
# logistic-normal composition and the multinomial counts:
#
#     xi_i    ~ Normal( m(g_i), Sigma ),   m_j(g) = log alpha_j(g) - Sigma_jj / 2
#     theta_i = softmax(xi_i)
#     p_i     ~ Dirichlet( kappa(g_i) * theta_i ),   kappa(g) = sum_j alpha_j(g)
#     Y_i     ~ Multinomial( n_i, p_i )
#
# Everything else (alpha from the CSV, Sigma from the 42 CD4 samples, the
# LOW/MED/HIGH perturbation, the 200 zeroed miRNAs, library size, output
# format) is unchanged. Lines that differ are marked "# DM-LN:".
# From any folder: Rscript /path/to/nbsr-experiments/paper/generate_data_DM_LN.R

rm(list=ls())

library(data.table)
library(seqinr)
library(MCMCpack)   # DM-LN: rdirichlet for the Dirichlet layer
script_arg <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
if (length(script_arg) == 0) stop("Run this file with Rscript")
script_file <- sub("^--file=", "", script_arg[1])
repo_dir <- normalizePath(file.path(dirname(script_file), ".."))

source(file.path(repo_dir, "paper", "dirichlet_estimation_functions.R"))
source(file.path(repo_dir, "paper", "functions.R"))
output_root <- file.path(repo_dir, "data", "DM-LN")   # DM-LN: new output folder

sample_counts <- 10
# sample_counts <- c(3, 5, 10)
zero_miRNA_count <- 200
rep_count <- 20
seq_depth <- 10^(6:8)
ks <- c(20, 10, 5)
log_folds <- c(1, 10)

# These alpha estimates were already fitted to the real microRNAome data,
# just as in generate_simulation_data.R.
miRNA_polya_est <- fread(file = file.path(repo_dir, "data", "microRNAome_dir_params.csv"))
# Select features from mirGeneDB.
mirGeneDB <- read.fasta(file = file.path(repo_dir, "data", "hsa.fas"))
miRNA_names <- names(mirGeneDB)

lowercase_string <- tolower(miRNA_names)
corrected_case_string <- sub("mir", "miR", lowercase_string)
mirGeneDB_final_string <- gsub("_", "-", corrected_case_string)

pattern <- "hsa-(let|miR)-[1-9][0-9]*"
mirGeneDB_prefixes <- unlist(regmatches(mirGeneDB_final_string, gregexpr(pattern, mirGeneDB_final_string)))

# Find the prefix for each miRNA.
miRNA_polya_est[,miRNA_prefix:=unlist(regmatches(miRNA, gregexpr(pattern, miRNA)))]
miRNA_polya_est <- miRNA_polya_est[miRNA_prefix %in% mirGeneDB_prefixes]

# Bin the miRNAs into groups: LOW, MED, HIGH.
celltype <- "t_lymphocyte_cd4"
dir_params <- miRNA_polya_est[cell_type == celltype & alpha_hat > 0]
miRNA_count <- nrow(dir_params)
idx_list <- list()
idx_list[["LOW"]] <- with(dir_params, which(alpha_hat > 1 & alpha_hat <= 10))
idx_list[["MED"]] <- with(dir_params, which(alpha_hat >= 10 & alpha_hat < 50))
idx_list[["HIGH"]] <- with(dir_params, which(alpha_hat > 50))

# Estimate the covariance of log proportions from the same 42 CD4 samples.
# Match the count rows to the alpha rows before calculating anything.
real_counts <- readRDS(file.path(repo_dir, "data", "microRNAome_cd4_counts.rds"))
stopifnot(all(dir_params$miRNA %in% rownames(real_counts)))
real_counts <- real_counts[dir_params$miRNA, , drop = FALSE]
expressed <- rowSums(real_counts) > 0

# DM-LN: pseudocount 0.5 instead of 1e-6. With 1e-6 a zero count maps to
# log p ~ -14 and sparse miRNAs get variances in the tens; the mean correction
# -Sigma_jj/2 below would then push those miRNAs to essentially zero.
# cov() centers each miRNA across samples; there is no extra CLR step.
real_props <- apply(real_counts + 0.5, 2, normalize)
Sigma <- cov(t(log(real_props)))

# All-zero miRNAs have no observed variation to estimate. Give them zero
# covariance rather than variation caused only by the pseudocount.
Sigma[!expressed, ] <- 0
Sigma[, !expressed] <- 0
dimnames(Sigma) <- list(dir_params$miRNA, dir_params$miRNA)
sigma_diag <- diag(Sigma)   # DM-LN: Sigma_jj, used in the mean correction
if (!dir.exists(output_root)) dir.create(output_root, recursive = TRUE)
saveRDS(Sigma, file.path(output_root, "Sigma.rds"))

for (ll in 1:length(idx_list))
{
  idx_set <- idx_list[[ll]]
  log_fc_values <- log_folds / (2^ll)
  test_name <- names(idx_list)[ll]
  k <- ks[ll]
  output_path <- file.path(output_root, test_name)

  for (rep_no in 1:rep_count)
  {
    # Each replicate has its own seed so it can be regenerated by itself.
    set.seed(1000 * ll + rep_no)

    alpha_null <- copy(dir_params)
    alpha_alt <- copy(dir_params)

    # Select k miRNAs, increase their abundance by fold.
    idxs <- sample(x = idx_set, size = k, replace = FALSE)
    fold_changes <- 2^runif(n = k, min = log_fc_values[1], max = log_fc_values[2])
    alpha_alt$alpha_hat[idxs] <- fold_changes * alpha_null$alpha_hat[idxs]

    # Give 200 low-abundance miRNAs a small baseline in both conditions.
    # As in the original script, 1e-3 does not force their counts to be zero.
    zero_out_idx <- sample(which(alpha_null$alpha_hat < 1 & alpha_alt$alpha_hat < 1),
                           zero_miRNA_count, replace = FALSE)

    alpha_alt[,alpha := alpha_hat]
    alpha_null[,alpha := alpha_hat]
    alpha_alt$alpha[zero_out_idx] <- alpha_null$alpha[zero_out_idx] <- 1e-3

    alpha_null[,alpha_bar := normalize(alpha)]
    alpha_alt[,alpha_bar := normalize(alpha)]

    # DM-LN: concentration of each condition, kappa(g) = sum_j alpha_j(g).
    kappa_null <- sum(alpha_null$alpha)
    kappa_alt <- sum(alpha_alt$alpha)

    # DM-LN: log-normal mean correction, m_j(g) = log alpha_j(g) - Sigma_jj/2,
    # so that E[exp(xi_ij)] = alpha_j(g).
    m_null <- log(alpha_null$alpha) - sigma_diag / 2
    m_alt <- log(alpha_alt$alpha) - sigma_diag / 2

    for (sample_count in sample_counts)
    {
      n <- 2 * sample_count
      rep_path <- file.path(output_path, paste0("sample_", sample_count),
                            paste0("rep", rep_no))

      # Sample xi directly with the same covariance in both conditions.
      # mvrnorm uses an eigen decomposition, so Sigma may be singular.
      xi_null <- MASS::mvrnorm(sample_count, mu = m_null, Sigma = Sigma)   # DM-LN: mean is m, not log alpha
      xi_alt <- MASS::mvrnorm(sample_count, mu = m_alt, Sigma = Sigma)
      xi <- t(rbind(xi_null, xi_alt))  # miRNAs x samples
      trt <- c(rep("null", sample_count), rep("alt", sample_count))
      kappa <- c(rep(kappa_null, sample_count), rep(kappa_alt, sample_count))   # DM-LN
      Y <- matrix(0, nrow = miRNA_count, ncol = n)
      p <- matrix(0, nrow = miRNA_count, ncol = n)   # DM-LN: Dirichlet draw, kept as truth
      lib_size <- rep(0, n)
      size_factor <- rep(0, n)

      for (i in 1:n)
      {
        theta_i <- exp(xi[, i] - max(xi[, i]))
        theta_i <- theta_i / sum(theta_i)

        # DM-LN: Dirichlet layer around the logistic-normal composition.
        p[, i] <- as.vector(rdirichlet(1, kappa[i] * theta_i))

        lib_size[i] <- runif(1, min = seq_depth[1], max = tail(seq_depth, 1))
        percent_miRNA <- runif(1, 0, 0.5)
        size_factor[i] <- ceiling(lib_size[i] * percent_miRNA)
        Y[,i] <- rmultinom(1, size = size_factor[i], prob = p[, i])   # DM-LN: counts from p, not theta
      }

      rownames(Y) <- dir_params$miRNA
      colnames(Y) <- paste0("Sample", 1:n)
      dimnames(xi) <- dimnames(Y)
      dimnames(p) <- dimnames(Y)
      X <- data.table(sample = paste0("Sample", 1:n), trt = trt,
                      lib_size = lib_size, miRNA_reads = size_factor)

      # Keep the original fc.csv fields. The postprocessor uses alpha_null
      # and alpha_alt to calculate the true absolute effect.
      fc <- data.table(miRNA = dir_params$miRNA,
                       alpha_null = alpha_null$alpha,
                       alpha_alt = alpha_alt$alpha,
                       alpha_null_bar = alpha_null$alpha_bar,
                       alpha_alt_bar = alpha_alt$alpha_bar)
      fc[,log2_fc := log2(alpha_alt_bar) - log2(alpha_null_bar)]
      fc[,log_fc := log(alpha_alt_bar) - log(alpha_null_bar)]
      fc[,absolute_fc := alpha_alt / alpha_null]
      # DM-LN: the three truths of Eq. 19. r_j equals log_fc above.
      fc[,delta := log(alpha_alt) - log(alpha_null)]
      fc[,c_rel := -log(kappa_alt / kappa_null)]
      fc[,r := delta + c_rel]

      # Output data to run NBSR, in the same format as the original script.
      if (!dir.exists(rep_path)) {
        dir.create(rep_path, recursive = TRUE)
      }
      row_idxs <- rowSums(Y > 0) > 1
      Y <- Y[row_idxs, , drop = FALSE]
      fc <- fc[row_idxs]
      xi <- xi[row_idxs, , drop = FALSE]
      p <- p[row_idxs, , drop = FALSE]
      X$miRNA_capture <- X$miRNA_reads / X$lib_size

      fwrite(X, file = file.path(rep_path, "X.csv"))
      write.table(Y, file = file.path(rep_path, "Y.csv"), quote = FALSE,
                  col.names = TRUE, row.names = TRUE, sep = ",")
      fwrite(fc, file = file.path(rep_path, "fc.csv"))

      # Keep the two latent layers as truth for later comparisons.
      write.table(xi, file = file.path(rep_path, "xi.csv"), quote = FALSE,
                  col.names = TRUE, row.names = TRUE, sep = ",")
      write.table(p, file = file.path(rep_path, "p.csv"), quote = FALSE,
                  col.names = TRUE, row.names = TRUE, sep = ",")
    }
  }
  cat("done:", test_name, "\n")
}

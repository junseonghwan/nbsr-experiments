     pch = 16, cex = 0.6, xlab = "PC1", ylab = "PC2",
     main = "Simulated gamma: HIGH rep 1")
legend("topright", legend = paste("Group", 1:L), col = colors[1:L],
       pch = 16, cex = 0.8)
